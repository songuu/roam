import { test, expect } from '@playwright/test';
import sharp from 'sharp';
import { readFile } from 'node:fs/promises';
import type { TravelPlan, Profile, JournalEntry } from '../../shared/types';
import { TravelApp } from './pages/travel-app';

test('从自然语言规划到图文记录、分享与偏好反馈的完整旅程', async ({ page }, testInfo) => {
  const errors: string[] = [];
  const app = new TravelApp(page);
  page.on('pageerror', error => errors.push(error.message));
  await app.open();
  await app.capture('desktop-home', testInfo);
  await page.getByLabel('描述你的旅行诉求').fill('从上海去成都玩四天，2026年11月6日出发，两大一小，总预算6000元，轻松一点，少辣，喜欢美食和博物馆，避开人潮');
  await page.getByRole('button', { name: '识别旅行诉求', exact: true }).click();
  await expect(page.getByLabel('目的地', { exact: true })).toHaveValue('成都');
  await expect(page.getByLabel('儿童', { exact: true })).toHaveValue('1');
  await expect(page.getByLabel('结束日期', { exact: true })).toHaveValue('2026-11-09');
  const creating = page.waitForResponse(response => response.url().endsWith('/api/trips') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '生成我的行程', exact: true }).click();
  const created = await creating;
  expect(created.status(), await created.text()).toBe(201);
  await expect(page.getByRole('tab', { name: /DAY 01/ })).toBeVisible();
  let plan = (await (await page.request.get('/api/trips')).json() as TravelPlan[])[0];
  expect(plan.days).toHaveLength(4);
  expect(plan.request.destination).toBe('成都');
  expect(plan.budget.total).toBeGreaterThan(0);
  await page.getByRole('tab', { name: /DAY 02/ }).click();
  await expect(page.getByRole('tab', { name: /DAY 02/ })).toHaveAttribute('aria-selected', 'true');
  await app.capture('itinerary', testInfo);
  await page.getByRole('button', { name: '模拟雨天重排', exact: true }).click();
  await expect.poll(async () => (await (await page.request.get(`/api/trips/${plan.id}`)).json() as TravelPlan).revision).toBe(2);
  plan = await (await page.request.get(`/api/trips/${plan.id}`)).json() as TravelPlan;
  expect(plan.days.every(day => day.weather.status === 'scenario')).toBe(true);
  await expect(page.getByRole('button', { name: '模拟雨天重排', exact: true })).toBeEnabled();
  await page.getByRole('tab', { name: /DAY 01/ }).click();
  const attraction = plan.days[0].stops.find(stop => stop.kind === 'attraction' && stop.tags.length)!;
  await page.getByRole('button', { name: `喜欢${attraction.name}`, exact: true }).click();
  await expect.poll(async () => (await (await page.request.get('/api/profile')).json() as Profile).feedbackCount).toBe(1);

  const exportedPath = testInfo.outputPath('travel.json');
  await app.download('下载数据 JSON', exportedPath);
  expect(JSON.parse(await readFile(exportedPath, 'utf8')).revision).toBe(2);

  await app.navigate('旅途手记');
  await page.getByLabel('手记标题').fill('慢慢走的一天');
  await page.getByLabel('旅途记载').fill('走了很舒服的绿道，吃了少辣晚餐，没有赶路。');
  const bitmap = await sharp({ create: { width: 300, height: 200, channels: 3, background: '#527a65' } }).png().toBuffer();
  await page.getByLabel('上传旅途照片').setInputFiles({ name: 'journey.png', mimeType: 'image/png', buffer: bitmap });
  await expect(page.getByRole('button', { name: '保存手记', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '保存手记', exact: true }).click();
  await expect(page.getByRole('heading', { name: '慢慢走的一天', exact: true })).toBeVisible();
  let entries = await (await page.request.get(`/api/trips/${plan.id}/journal`)).json() as JournalEntry[];
  expect(entries).toHaveLength(1);
  expect(entries[0].photos).toHaveLength(1);
  expect((await page.request.get(entries[0].photos[0].url)).status()).toBe(200);

  await app.navigate('分享工作室');
  await expect(page.getByRole('button', { name: '生成分享文案', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '生成分享文案', exact: true }).click();
  await expect(page.getByLabel('分享正文')).toHaveValue(/绿道/);
  expect(await page.getByLabel('分享正文').inputValue()).toContain('少辣晚餐');
  await page.getByLabel('分享标题').fill('我的成都慢旅行');
  await app.download('下载图文卡片', testInfo.outputPath('share-card.png'));
  const card = await sharp(testInfo.outputPath('share-card.png')).metadata();
  expect(card.format).toBe('png');
  expect(card.width).toBeGreaterThan(0);
  expect(card.height).toBeGreaterThan(0);
  await testInfo.attach('share-card', { path: testInfo.outputPath('share-card.png'), contentType: 'image/png' });
  await app.capture('share-studio', testInfo);
  await page.getByRole('button', { name: /朋友圈.*给朋友/ }).click();
  await page.getByRole('button', { name: '生成分享文案', exact: true }).click();
  await expect(page.getByLabel('分享正文')).toHaveValue(/绿道/);
  expect(await page.getByLabel('分享正文').inputValue()).toContain('绿道');
  const wechatPath = testInfo.outputPath('wechat.txt');
  await app.download('下载文案', wechatPath);
  expect(await readFile(wechatPath, 'utf8')).toContain('绿道');

  await app.navigate('旅行偏好');
  await page.getByLabel('如何称呼你').fill('慢旅行的朋友');
  await page.getByRole('button', { name: '保存旅行偏好', exact: true }).click();
  await expect.poll(async () => (await (await page.request.get('/api/profile')).json() as Profile).displayName).toBe('慢旅行的朋友');
  await page.getByRole('button', { name: '清除推断偏好', exact: true }).click();
  await expect.poll(async () => (await (await page.request.get('/api/profile')).json() as Profile).feedbackCount).toBe(0);
  await page.reload();
  await expect(page.getByRole('button', { name: '生成我的行程', exact: true })).toBeEnabled();
  await app.navigate('旅途手记');
  await expect(page.getByRole('heading', { name: '慢慢走的一天', exact: true })).toBeVisible();
  entries = await (await page.request.get(`/api/trips/${plan.id}/journal`)).json() as JournalEntry[];
  expect(entries[0].content).toContain('绿道');
  expect((await (await page.request.get('/api/profile')).json() as Profile).displayName).toBe('慢旅行的朋友');
  expect(errors).toEqual([]);
});

test('未知目的地错误可见，移动端没有横向溢出', async ({ page }, testInfo) => {
  const app = new TravelApp(page);
  await page.setViewportSize({ width: 390, height: 844 });
  await app.open();
  await app.capture('mobile-home', testInfo);
  await app.expectNoHorizontalOverflow();
  await page.getByRole('button', { name: '完善旅行诉求', exact: true }).click();
  await page.getByLabel('目的地', { exact: true }).fill('未收录测试城');
  await page.getByRole('button', { name: '生成我的行程', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('暂未收录');
  await expect(page.getByRole('button', { name: '生成我的行程', exact: true })).toBeEnabled();
  await app.expectNoHorizontalOverflow();
});
